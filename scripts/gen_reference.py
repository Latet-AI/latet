def _page(title: str, description: str, body: list[str]) -> str:
    head = ["---", f"title: {title}", f"description: {description}", "---", "", NOTICE, ""]
    return "\n".join(head + body).rstrip("\n") + "\n"


_OPTION = re.compile(r"(?<![\w`-])(--[a-z][a-z0-9-]*)")


def _prose(text: str) -> str:
    """Options a help text names, as code: Markdown would turn their two hyphens into a dash."""
    parts = re.split(r"(`[^`]*`)", text)
    return "".join(p if p.startswith("`") else _OPTION.sub(r"`\1`", p) for p in parts)


def _cell(text: str) -> str:
    return " ".join(_prose(str(text)).split()).replace("|", "\\|")


# --- CLI ---------------------------------------------------------------------------------------------


def _default(param: Any) -> str:
    if param.is_flag:
        if param.default is None:
            return "asks"  # a question the command asks unless the flag (or --yes) answers it
        return "on" if param.default else "off"
    if param.default is None or param.default == "":
        return ""
    return f"`{param.default}`"


def _argument_rows(command: Any) -> list[str]:
    rows = []
    for param in command.params:
        if param.param_type_name == "argument":
            name = f"`{param.name.upper()}`" + ("..." if param.nargs == -1 else "")
            needed = "required" if param.required else "optional"
            rows.append(f"| {name} | {needed} | {_cell(getattr(param, 'help', '') or '')} |")
    return rows


def _option_rows(command: Any) -> list[str]:
    # Typer ships its own copy of click: duck typing, not isinstance.
    rows = []
    for param in command.params:
        if param.param_type_name != "option" or param.hidden or param.name == "help":
            continue
        names = ", ".join(f"`{o}`" for o in [*param.opts, *param.secondary_opts])
        kind = {"STR": "TEXT", "INTEGER": "INT"}.get(param.type.name.upper(), param.type.name.upper())
        metavar = "" if param.is_flag else f" `{kind}`"
        rows.append(f"| {names}{metavar} | {_default(param)} | {_cell(param.help or '')} |")
    return rows


def _commands(group: Any, prefix: str) -> list[tuple[str, Any]]:
    """Every command, and every group that runs on its own or takes options of its own (given before a command's
    name, such as `latet server --server URL people list`), with its full name."""
    out = []
    for name, command in group.commands.items():
        if command.hidden:
            continue
        full = f"{prefix} {name}"
        if hasattr(command, "commands"):
            if command.invoke_without_command or _option_rows(command) or _argument_rows(command):
                out.append((full, command))
            out += _commands(command, full)
        else:
            out.append((full, command))
    return out


def cli_page() -> str:
    commands = _commands(typer.main.get_command(app), "latet")
    body = ["| Command | What it does |", "| --- | --- |"]
    body += [f"| `{name}` | {_cell((c.help or '').strip().split(chr(10) * 2, 1)[0])} |" for name, c in commands]
    for name, command in commands:
        body += ["", f"## `{name}`", "", _prose((command.help or "").strip())]
        if command.context_settings.get("ignore_unknown_options"):
            body += ["", "Every other argument is passed to the command as is."]
        if hasattr(command, "commands") and not command.invoke_without_command:
            body += ["", f"Its options go before the name of one of its commands: `{name} [OPTIONS] COMMAND`."]
        arguments = _argument_rows(command)
        if arguments:
            body += ["", "| Argument | | Description |", "| --- | --- | --- |", *arguments]
        rows = _option_rows(command)
        if rows:
            body += ["", "| Option | Default | Description |", "| --- | --- | --- |", *rows]
    return _page("CLI", "Reference for the latet command line.", body)


