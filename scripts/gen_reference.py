def _type(annotation: Any) -> str:
    origin, args = typing.get_origin(annotation), typing.get_args(annotation)
    if origin is typing.Annotated:  # a type with a check of its own (an allow pattern RE2 compiles): the type
        return _type(args[0])
    if origin is typing.Literal:
        return " or ".join(f"`{a}`" for a in args)
    if origin in (typing.Union, types.UnionType):
        return " or ".join(_type(a) for a in args if a is not type(None))  # unset: see the default
    if origin is list:
        return f"list of {_type(args[0])}"
    if origin is dict:
        return f"map of {_type(args[0])} to {_type(args[1])}"
    if isinstance(annotation, type):
        if issubclass(annotation, enum.Enum):
            return " or ".join(f"`{m.value}`" for m in annotation)
        if issubclass(annotation, BaseModel):
            return "object"
        if issubclass(annotation, PurePath):
            return "path"
        return {"str": "text", "int": "number", "bool": "true or false"}.get(annotation.__name__, annotation.__name__)
    return str(annotation)


def _value(field: Any) -> str:
    if field.default_factory is not None:
        value = field.default_factory()
    elif field.default is PydanticUndefined:
        return "required"
    else:
        value = field.default
    if isinstance(value, BaseModel):
        return "see below"
    if value is None:
        return "not set"
    if hasattr(value, "value"):
        value = value.value
    return f"`{yaml.safe_dump(value, default_flow_style=True).strip().removesuffix('...').strip()}`"


# Keys whose annotation says less than the file accepts: (type, default) as shown.
_SHOWN = {
    (Config, "auto_mode_review"): ("`block`, `allow-identity` or object", "`block`"),
    (Config, "recognizers"): ("list of objects (see below)", "`[]`"),
}


def _fields(model: type[BaseModel], skip: tuple[str, ...] = (), only: tuple[str, ...] | None = None) -> list[str]:
    rows = ["| Key | Type | Default | Description |", "| --- | --- | --- | --- |"]
    for name, field in model.model_fields.items():
        if name in skip or (only is not None and name not in only):
            continue
        kind, default = _SHOWN.get((model, name)) or (_type(field.annotation), _value(field))
        rows.append(f"| `{field.alias or name}` | {kind} | {default} | {_cell(field.description or '')} |")
    return rows


