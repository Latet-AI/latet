def schema_file() -> str:
    from latet.schema import config_schema

    return json.dumps(config_schema(), indent=2, ensure_ascii=False) + "\n"


def project_schema_file() -> str:
    from latet.schema import project_schema

    return json.dumps(project_schema(), indent=2, ensure_ascii=False) + "\n"


def rules_schema_file() -> str:
    from latet.schema import rules_schema

    return json.dumps(rules_schema(), indent=2, ensure_ascii=False) + "\n"


PAGES = {
    "cli.md": cli_page,
    "configuration.md": configuration_page,
    "detectors.md": detectors_page,
    "../../../../public/config.schema.json": schema_file,
    "../../../../public/project.schema.json": project_schema_file,
    "../../../../public/rules.schema.json": rules_schema_file,
}


def main() -> int:
    stale = []
    for name, render in PAGES.items():
        target = (REFERENCE / name).resolve()
        text = render()
        if "--check" in sys.argv:
            if not target.exists() or target.read_text("utf-8") != text:
                stale.append(name)
            continue
        target.write_text(text, "utf-8", newline="\n")
        print(f"wrote {target.relative_to(ROOT)}")
    if stale:
        print(f"out of date: {', '.join(stale)}; run `uv run python scripts/gen_reference.py`")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
